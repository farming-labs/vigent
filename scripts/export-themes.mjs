#!/usr/bin/env node
/**
 * Write the built-in themes (src/builtin-themes.ts, built into dist/) as plain
 * text the Rust vigent embeds: crates/vigent/src/themes.txt. One theme per
 * block, so both versions draw from the same colors:
 *
 *   theme <name> <dark|light> <transparent|solid>
 *   @palette <json>                      the palette it was built from, when it was
 *   @style <json>                        its [style] (layout and icons), when it has one
 *   <Group> <fg|-> <bg|-> <flags|->      flags: b(old) i(talic) u(nderline) r(everse)
 *
 *   node scripts/export-themes.mjs           write it
 *   node scripts/export-themes.mjs --check   fail if it's out of date (npm test runs this)
 */
import * as fs from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = `${root}crates/vigent/src/themes.txt`;
const { BUILTIN_THEMES } = await import(`${root}dist/builtin-themes.js`);

export function themesText(themes = BUILTIN_THEMES) {
	const lines = ["# generated by scripts/export-themes.mjs from src/builtin-themes.ts; don't edit"];
	for (const t of Object.values(themes)) {
		lines.push(`theme ${t.name} ${t.background ?? "dark"} ${t.transparent ? "transparent" : "solid"}`);
		if (t.palette) lines.push(`@palette ${JSON.stringify(t.palette)}`);
		if (t.style) lines.push(`@style ${JSON.stringify(t.style)}`);
		for (const [group, a] of Object.entries(t.groups)) {
			const flags = `${a.bold ? "b" : ""}${a.italic ? "i" : ""}${a.underline ? "u" : ""}${a.reverse ? "r" : ""}` || "-";
			lines.push(`${group} ${a.fg ?? "-"} ${a.bg ?? "-"} ${flags}`);
		}
	}
	return lines.join("\n") + "\n";
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const text = themesText();
	if (process.argv.includes("--check")) {
		if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== text) {
			console.error("crates/vigent/src/themes.txt is out of date: run  node scripts/export-themes.mjs");
			process.exit(1);
		}
	} else fs.writeFileSync(out, text);
}
